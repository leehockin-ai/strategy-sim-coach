import { PGlite } from "@electric-sql/pglite";
import { readFileSync } from "node:fs";
import { expect, it } from "vitest";
it("isolated Gmail outbox CAS prevents duplicate/crash retries, keeps ownership and new-only capture", async () => {
  const db = new PGlite();
  const session = "11111111-1111-4111-8111-111111111111", owner = "22222222-2222-4222-8222-222222222222", id = "33333333-3333-4333-8333-333333333333", token = "44444444-4444-4444-8444-444444444444";
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role; CREATE SCHEMA auth;
      CREATE TABLE auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
      CREATE TABLE sessions(id uuid primary key,owner_id uuid,submission_requested_at timestamptz);
      CREATE TABLE evaluations(id uuid primary key,session_id uuid references sessions(id),reviewer_decision text);
      INSERT INTO auth.users VALUES('${owner}','coach@example.test',now());
      INSERT INTO sessions VALUES('${session}','${owner}',now());
      INSERT INTO evaluations VALUES(gen_random_uuid(),'${session}',NULL);`);
    await db.exec(readFileSync("docs/unapplied/assessment-ready-mail.sql", "utf8"));
    await db.exec(readFileSync("docs/unapplied/assessment-gmail-outcomes.sql", "utf8"));
    expect((await db.query("select * from assessment_ready_outbox")).rows).toHaveLength(0);
    await db.query("insert into evaluations values($1,$2,NULL)", [id, session]);
    const claim = await db.query<{ r: { owner_id: string; pending_human_review: boolean } }>("select claim_assessment_ready($1,$2) r", [id, token]);
    expect(claim.rows[0].r).toMatchObject({ owner_id: owner, pending_human_review: true });
    expect((await db.query<{ r: boolean }>("select begin_assessment_gmail_send($1,gen_random_uuid()) r", [id])).rows[0].r).toBe(false);
    expect((await db.query<{ r: boolean }>("select begin_assessment_gmail_send($1,$2) r", [id, token])).rows[0].r).toBe(true);
    expect((await db.query<{ r: boolean }>("select begin_assessment_gmail_send($1,$2) r", [id, token])).rows[0].r).toBe(false);
    await db.query("update assessment_ready_outbox set lease_until=now()-interval '1 hour' where assessment_id=$1", [id]);
    expect((await db.query<{ r: unknown }>("select claim_assessment_ready($1,gen_random_uuid()) r", [id])).rows[0].r).toBeNull();
    expect((await db.query<{ r: boolean }>("select settle_assessment_ready($1,$2,'ambiguous') r", [id, token])).rows[0].r).toBe(true);
    expect((await db.query<{ r: unknown }>("select claim_assessment_ready($1,gen_random_uuid()) r", [id])).rows[0].r).toBeNull();
    expect((await db.query<{ r: boolean }>("select settle_assessment_ready($1,$2,'retry') r", [id, token])).rows[0].r).toBe(false);
    await db.exec("SET ROLE service_role");
    await expect(db.query("select claim_assessment_ready_managed($1,$2)", [id, token])).rejects.toThrow("permission denied");
    await db.exec("RESET ROLE; SET ROLE authenticated");
    await expect(db.query("select begin_assessment_gmail_send($1,$2)", [id, token])).rejects.toThrow("permission denied");
    await expect(db.query("select * from assessment_ready_outbox")).rejects.toThrow("permission denied");
    await db.exec("RESET ROLE");
    const next = "55555555-5555-4555-8555-555555555555";
    await db.query("insert into evaluations values($1,$2,NULL)", [next, session]);
    await db.query("select claim_assessment_ready($1,$2)", [next, token]);
    await db.query("select begin_assessment_gmail_send($1,$2)", [next, token]);
    expect((await db.query<{ r: boolean }>("select settle_assessment_ready($1,$2,'accepted') r", [next, token])).rows[0].r).toBe(true);
    expect((await db.query<{ r: unknown }>("select claim_assessment_ready($1,gen_random_uuid()) r", [next])).rows[0].r).toBeNull();
    const retryId = "66666666-6666-4666-8666-666666666666";
    await db.query("insert into evaluations values($1,$2,NULL)", [retryId, session]);
    await db.query("select claim_assessment_ready($1,$2)", [retryId, token]);
    await db.query("select begin_assessment_gmail_send($1,$2)", [retryId, token]);
    expect((await db.query<{ r: boolean }>("select settle_assessment_ready($1,$2,'retry') r", [retryId, token])).rows[0].r).toBe(true);
    expect((await db.query<{ r: unknown }>("select claim_assessment_ready($1,gen_random_uuid()) r", [retryId])).rows[0].r).toBeNull();
    await db.query("update assessment_ready_outbox set retry_after=now()-interval '1 hour' where assessment_id=$1", [retryId]);
    await db.exec("update auth.users set email='changed@example.test'");
    expect((await db.query<{ r: unknown }>("select claim_assessment_ready($1,gen_random_uuid()) r", [retryId])).rows[0].r).toBeNull();
    expect((await db.query<{ status: string }>("select status from assessment_ready_outbox where assessment_id=$1", [retryId])).rows[0].status).toBe("blocked");
  } finally { await db.close(); }
}, 120000);